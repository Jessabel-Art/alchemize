export const appendCustomDocumentOption = (items = []) => {
  const seen = new Set(items.map((item) => item.value));
  if (!seen.has("custom_document")) {
    items.push({
      value: "custom_document",
      label: documentTypeCatalog.custom_document.label,
    });
  }
  return items;
};

export const getDocumentTypeOptionsForService = (serviceCode = "") => {
  const normalized = String(serviceCode || "")
    .trim()
    .toLowerCase()
    .replace(/_/g, "-");

  const catalogKey =
    serviceAliasMap[normalized] ||
    normalized.replace(/[^a-z0-9-]+/g, "-").replace(/^-|-$/g, "");
  const values = serviceTypeCatalog[catalogKey] || [];

  if (values.length === 0) {
    return [
      {
        value: "custom_document",
        label: documentTypeCatalog.custom_document.label,
      },
    ];
  }

  return appendCustomDocumentOption(
    values.map((value) => ({
      value,
      label:
        documentTypeCatalog[value]?.label ||
        value
          .replace(/_/g, " ")
          .replace(/\b\w/g, (letter) => letter.toUpperCase()),
    })),
  );
};

export const getDocumentTypeOptionsForEngagement = (
  engagement = {},
  servicesById = {},
) => {
  const serviceId = engagement?.serviceId || engagement?.service_id;
  const serviceCode =
    engagement?.serviceCode ||
    engagement?.service_code ||
    servicesById?.byId?.[serviceId]?.serviceCode ||
    servicesById?.byId?.[serviceId]?.service_code ||
    "";

  return getDocumentTypeOptionsForService(serviceCode);
};
